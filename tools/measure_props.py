"""Measure the visible size of world props for FEATURES.sizeAware (layering, collision and slow by size).

Collision and slow radii come from the opaque pixels of each prop sprite, so new or redrawn art gets the right
footprint by re-running this script instead of hand-tuning numbers. Only the *kind* of each prop (solid, soft,
canopy, ground) is a hand choice, in KINDS below.

  python tools/measure_props.py          # rewrite the PROP_SIZE line in PRIMAL_RUN_Game/src/core.js
  python tools/measure_props.py --check  # exit 1 when core.js is stale (used by tests/size-aware.test.cjs)
"""
import json, re, sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1] / 'PRIMAL_RUN_Game'
CORE = ROOT / 'src' / 'core.js'
# solid: blocks movement like a rock. soft: slows and hides (bush cover). canopy: drawn above animals, which shine
# through. ground: flat, drawn under animals, no effect on movement.
KINDS = {
    'assets/environment/rock.png': 'solid', 'assets/props/boulder_large.png': 'solid', 'assets/props/lava_rock.png': 'solid',
    'assets/props/meteorite.png': 'solid',
    'assets/props/fern_large.png': 'soft', 'assets/props/flower_bush.png': 'soft', 'assets/ecology/shrub.png': 'soft',
    'assets/ecology/fruit_bush.png': 'soft', 'assets/ecology/broad_fern.png': 'soft', 'assets/ecology/seed_fern.png': 'soft',
    'assets/ecology/cycad.png': 'soft', 'assets/ecology/horsetail.png': 'soft', 'assets/ecology/reeds.png': 'soft',
    'assets/props/tree_canopy.png': 'canopy', 'assets/props/dead_tree.png': 'canopy', 'assets/ecology/conifer.png': 'canopy',
    'assets/environment/fern.png': 'ground', 'assets/props/fallen_log.png': 'ground', 'assets/props/nest_eggs.png': 'ground',
    'assets/props/nest_empty.png': 'ground', 'assets/props/skull.png': 'ground', 'assets/ecology/moss.png': 'ground',
    'assets/ecology/lichen.png': 'ground', 'assets/ecology/leaf_litter.png': 'ground', 'assets/ecology/twigs.png': 'ground',
    'assets/ecology/roots.png': 'ground', 'assets/ecology/mushrooms.png': 'ground', 'assets/ecology/flowers.png': 'ground',
    'assets/ecology/dry_grass.png': 'ground', 'assets/ecology/succulent.png': 'ground', 'assets/ecology/herb.png': 'ground',
}

def measure(path):
    """Radius of the visible body: mean of half the opaque width and height (alpha > 16), rounded."""
    im = Image.open(ROOT / path).convert('RGBA')
    box = im.getchannel('A').point(lambda a: 255 if a > 16 else 0).getbbox()
    return round(((box[2] - box[0]) + (box[3] - box[1])) / 4)

def line():
    table = {p: [KINDS[p], measure(p)] for p in sorted(KINDS)}
    return '  const PROP_SIZE=' + json.dumps(table, separators=(',', ':')) + '; // generated by tools/measure_props.py: [kind, visible radius px]'

def main():
    src = CORE.read_text(encoding='utf-8')
    new, n = re.subn(r'^  const PROP_SIZE=.*$', line(), src, count=1, flags=re.M)
    if n != 1: sys.exit('PROP_SIZE line not found in core.js')
    if '--check' in sys.argv:
        if new != src: sys.exit('core.js PROP_SIZE is stale: run python tools/measure_props.py')
        print('PROP_SIZE up to date'); return
    CORE.write_text(new, encoding='utf-8'); print(line())

if __name__ == '__main__':
    main()
